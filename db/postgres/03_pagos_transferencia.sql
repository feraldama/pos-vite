-- ============================================================================
-- Pagos por transferencia
-- Fecha: 2026-10-22
--
--   pagotransferencia  cada pago que el negocio hace por transferencia
--                      bancaria: a quién, por qué, desde qué cuenta, con el
--                      comprobante adjunto. No pasa por la caja: el cierre de
--                      caja no lo ve.
--   menu               "PAGOS TRANSFERENCIA", para asignarlo a los perfiles
--                      que no son administradores.
--
-- La categoría es un grupo de egreso de Tipos de gasto (TipoGastoId = 1).
--
-- Idempotente: se puede volver a correr sin romper nada.
-- En producción correrla con el rol dueño de las tablas (decorpar_app).
-- ============================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS pagotransferencia (
    "PagoTransferenciaId"   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PagoFecha"             date NOT NULL,
    "PagoMonto"             bigint NOT NULL CHECK ("PagoMonto" > 0),
    "PagoBeneficiario"      varchar(100) NOT NULL,
    "PagoConcepto"          varchar(250) NOT NULL,
    "TipoGastoId"           integer DEFAULT 1 NOT NULL CHECK ("TipoGastoId" = 1),
    "TipoGastoGrupoId"      smallint NOT NULL,
    "PagoCuentaOrigen"      varchar(60) DEFAULT '' NOT NULL,
    "PagoNumeroOperacion"   varchar(60) DEFAULT '' NOT NULL,
    "PagoComprobante"       bytea,
    "PagoComprobanteTipo"   varchar(100) DEFAULT '' NOT NULL,
    "PagoComprobanteNombre" varchar(150) DEFAULT '' NOT NULL,
    -- Quien cargó el pago (es quien lo hizo)
    "UsuarioId"             varchar(25) NOT NULL REFERENCES usuario ("UsuarioId"),
    "PagoFechaCarga"        timestamptz DEFAULT now() NOT NULL,
    FOREIGN KEY ("TipoGastoId", "TipoGastoGrupoId")
        REFERENCES tipogastogrupo ("TipoGastoId", "TipoGastoGrupoId")
);

CREATE INDEX IF NOT EXISTS "IPAGOTRANSFERENCIA_FECHA" ON pagotransferencia ("PagoFecha");
CREATE INDEX IF NOT EXISTS "IPAGOTRANSFERENCIA_USUARIO" ON pagotransferencia ("UsuarioId", "PagoFecha");

INSERT INTO menu ("MenuId", "MenuNombre")
SELECT 'PagosTransferencia', 'PAGOS TRANSFERENCIA'
WHERE NOT EXISTS (SELECT 1 FROM menu WHERE "MenuNombre" = 'PAGOS TRANSFERENCIA');

COMMIT;
